package com.foodflow.repository;

import com.foodflow.document.NGOMatchingDocument;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.mongodb.repository.MongoRepository;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;

@Repository
public interface NGOMatchingRepository extends MongoRepository<NGOMatchingDocument, String> {
    
    // Retrieve the latest matching recommendation run for a specific donation
    Optional<NGOMatchingDocument> findTopByDonationIdOrderByCreatedAtDesc(String donationId);
    
    // Find all matching runs for a specific donation (useful for audit history)
    List<NGOMatchingDocument> findByDonationIdOrderByCreatedAtDesc(String donationId);
    
    // Retrieve history of matchings generated by a specific restaurant, sorted most-recent-first
    Page<NGOMatchingDocument> findByRestaurantIdOrderByCreatedAtDesc(String restaurantId, Pageable pageable);
    
    // Retrieve all matchings for admin history, sorted most-recent-first
    Page<NGOMatchingDocument> findAllByOrderByCreatedAtDesc(Pageable pageable);
}
