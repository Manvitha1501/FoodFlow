package com.foodflow.algorithm;

import com.foodflow.document.DonationDocument;
import com.foodflow.document.EmbeddedAllocation;
import com.foodflow.document.NgoProfileDocument;
import com.foodflow.document.RankedNGO;

import java.util.List;
import java.util.Map;

/**
 * Strategy interface for multi-NGO food allocation splitting.
 * 
 * <p>Responsibility Boundary:</p>
 * <ul>
 *   <li><b>Strategy Layer:</b> Performs pure mathematical splitting allocation based on capacities
 *   and suitability matching ranks. Returns the calculated list of allocation segments.</li>
 *   <li><b>Service Layer:</b> Performs data loading, validation, state/status persistence, 
 *   and security role access checks.</li>
 * </ul>
 */
public interface AllocationStrategy {

    /**
     * Allocates a donation's quantities across available NGOs.
     * 
     * @param donation The donation details (total quantity and unit).
     * @param activeNgosMap Map of active NGO profile documents, keyed by their NGO profile ID.
     * @param matchingRanks List of ranked suitability results generated by Module 6.
     * @return List of calculated allocations for participating NGOs.
     */
    List<EmbeddedAllocation> allocate(
        DonationDocument donation,
        Map<String, NgoProfileDocument> activeNgosMap,
        List<RankedNGO> matchingRanks
    );
}
